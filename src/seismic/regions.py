"""Сейсмоактивные зоны: упрощённое районирование прямоугольниками широты/долготы.

Это приближение (в сейсмологии используют районирование Флинна–Энгдаля),
но оно прозрачно, воспроизводимо и достаточно для сравнения крупных
зон субдукции и коллизии. Зоны проверяются по порядку: первая подходящая
побеждает, поэтому более узкие зоны стоят выше.
"""

import numpy as np
import pandas as pd

# (id, название, тип границы плит, [(lat_min, lat_max, lon_min, lon_max), ...])
ZONES = [
    (1, "Япония, Курилы, Камчатка", "субдукция", [(30, 62, 128, 165)]),
    (2, "Алеуты и Аляска", "субдукция", [(50, 72, 165, 180), (50, 72, -180, -130)]),
    (3, "Филиппины и Тайвань", "субдукция", [(5, 26, 116, 128)]),
    (14, "Марианские о-ва и Идзу-Бонин", "субдукция", [(10, 30, 135, 150)]),
    (4, "Индонезия", "субдукция", [(-12, 6, 90, 130)]),
    (5, "Новая Гвинея и Соломоновы о-ва", "субдукция", [(-12, 0, 130, 165)]),
    (6, "Новая Зеландия", "субдукция", [(-50, -37, 165, 180)]),
    (7, "Тонга, Фиджи, Вануату, Кермадек", "субдукция",
     [(-40, -10, 160, 180), (-40, -10, -180, -170)]),
    (8, "Анды (Чили, Перу, Эквадор)", "субдукция", [(-60, 5, -82, -60)]),
    (9, "Мексика и Центральная Америка", "субдукция", [(5, 33, -120, -77)]),
    (10, "Карибский регион", "субдукция", [(10, 22, -77, -59)]),
    (11, "Запад США и Канады", "трансформная", [(32, 60, -135, -114)]),
    (12, "Средиземноморье и Ближний Восток", "коллизия", [(28, 48, -10, 62)]),
    (13, "Гималаи, Центральная Азия, Китай", "коллизия", [(20, 55, 62, 125)]),
]
OTHER_ZONE = (99, "Прочие (океанические хребты и др.)", "разные", [])


def zones_frame() -> pd.DataFrame:
    rows = [(zid, name, kind) for zid, name, kind, _ in ZONES + [OTHER_ZONE]]
    return pd.DataFrame(rows, columns=["zone_id", "name", "boundary_type"])


def assign_zone(lat: np.ndarray, lon: np.ndarray) -> np.ndarray:
    """Векторное присвоение зоны: маска на каждый прямоугольник, первая победа."""
    lat = np.asarray(lat, dtype=float)
    lon = np.asarray(lon, dtype=float)
    result = np.full(lat.shape, OTHER_ZONE[0], dtype=np.int16)
    unassigned = np.ones(lat.shape, dtype=bool)
    for zone_id, _, _, boxes in ZONES:
        inside = np.zeros(lat.shape, dtype=bool)
        for lat_min, lat_max, lon_min, lon_max in boxes:
            inside |= (lat >= lat_min) & (lat < lat_max) & (lon >= lon_min) & (lon <= lon_max)
        hit = inside & unassigned
        result[hit] = zone_id
        unassigned &= ~hit
    return result
